# -*- coding: utf-8 -*-
"""
系统原则蓝图：全站最简单的一个页面，就是把一份手写的交易原则清单列出来，没有数据库、
没有查询、没有计算。这些原则是这个系统设计理念的一部分背景（比如"方向判断只占20%，
仓位管理占40%"这一条，呼应了品种详情页"决策参考"卡片为什么只给方向对齐提示、
不给仓位/资金管理建议——系统本来就认为方向不是决策里最重要的那部分）。

PRINCIPLES 目前是硬编码在这个文件里的 Python 列表，不是数据库表——因为这些是很少变动的
"方法论"文字，不需要为了几条固定文本专门建一张表、走一遍 CRUD。如果以后想让这份清单
能在 /admin 里编辑，可以参照 Policy 表的做法单独建一张表，把这里的硬编码列表迁移过去，
但目前的量级(5条)没有这个必要。
"""
from flask import Blueprint, render_template

principles_bp = Blueprint("principles", __name__)

PRINCIPLES = [
    '市场交易的不是"绝对价格"，而是"价格的方向和速率"。',
    '交易的本质不是预测方向，而是资金管理。方向判断占20%，仓位管理占40%，现金流占40%。',
    '找出谁是"被动的一方"。行情往往由"被迫行动"的投资者驱动。',
    '方向是"空"，但入场要等"反弹"。不追空，等反弹衰竭再空。',
    '买近抛远，是逼空/逼多行情中的经典操作。',
]


@principles_bp.route("/")
def principles():
    return render_template("principles/principles.html", principles=PRINCIPLES)
